import 'package:aelmamclinic/utils/app_locale.dart';
import 'package:intl/intl.dart';

String trRaw(String raw) => RawStringLocalizer.translateWithCurrentLocale(raw);

abstract final class RawStringLocalizer {
  static String translate(String raw, {required String languageCode}) {
    if (raw.isEmpty) return raw;
    if (AppLocale.normalize(languageCode) == AppLocale.arabicLanguageCode) {
      return raw;
    }

    final normalized = _normalize(raw);
    final exact = _exact[normalized];
    if (exact != null && exact.isNotEmpty) {
      return exact;
    }

    var output = _translateStructured(raw);

    output = output
        .replaceAll('،', ', ')
        .replaceAll('؛', '; ')
        .replaceAll('؟', '?')
        .replaceAll('…', '...')
        .replaceAll('٪', '%')
        .replaceAll('  ', ' ');

    return output;
  }

  static String translateWithCurrentLocale(String raw) {
    return translate(
      raw,
      languageCode: Intl.defaultLocale ?? AppLocale.defaultLanguageCode,
    );
  }

  static String _normalize(String value) {
    return value
        .replaceAll('\u200f', '')
        .replaceAll('\u200e', '')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
  }

  static String _translateStructured(String raw) {
    final parts = raw.splitMapJoin(
      RegExp(r'(\n|•)'),
      onMatch: (match) => match.group(0) ?? '',
      onNonMatch: (segment) => _translateSegment(segment),
    );
    return parts;
  }

  static String _translateSegment(String segment) {
    if (segment.trim().isEmpty) return segment;

    final normalized = _normalize(segment);
    final exact = _exact[normalized];
    if (exact != null && exact.isNotEmpty) {
      return exact;
    }

    final leadingMatch = RegExp(r'^\s*').firstMatch(segment);
    final trailingMatch = RegExp(r'\s*$').firstMatch(segment);
    final leading = leadingMatch?.group(0) ?? '';
    final trailing = trailingMatch?.group(0) ?? '';
    var core = segment.substring(
      leading.length,
      segment.length - trailing.length,
    );

    if (core.isEmpty) {
      return segment;
    }

    var changed = true;
    while (changed) {
      changed = false;
      for (final entry in _orderedGlossary) {
        final next = _replaceBoundary(core, entry.key, entry.value);
        if (next != core) {
          core = next;
          changed = true;
        }
      }

      final translated = _exact[_normalize(core)];
      if (translated != null && translated.isNotEmpty) {
        core = translated;
        break;
      }
    }

    return '$leading$core$trailing';
  }

  static String _replaceBoundary(String input, String source, String target) {
    if (input.isEmpty || source.isEmpty) return input;
    if (input == source) return target;

    var output = input;
    if (output.startsWith(source)) {
      output = '$target${output.substring(source.length)}';
    }
    if (output.endsWith(source)) {
      output = '${output.substring(0, output.length - source.length)}$target';
    }
    return output;
  }

